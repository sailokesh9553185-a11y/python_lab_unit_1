# Program to perform list operations: append, insert, remove, sort, reverse

my_list = [40, 10, 30, 20]
print("Original List:", my_list)

# 1. Append an element to the end
my_list.append(50)
print("After append(50):", my_list)

# 2. Insert an element at a specific index
my_list.insert(1, 15)
print("After insert(1, 15):", my_list)

# 3. Remove an element by value
my_list.remove(30)
print("After remove(30):", my_list)

# 4. Sort the list in ascending order
my_list.sort()
print("After sort():", my_list)

# 5. Reverse the list
my_list.reverse()
print("After reverse():", my_list)
