print("--- Operator Precedence and Associativity Demonstration ---")

result1 = 10 + 3 * 2
print(f"10 + 3 * 2 = {result1}")

result2 = (10 + 3) * 2
print(f"(10 + 3) * 2 = {result2}")

result3 = 20 - 5 - 3
print(f"20 - 5 - 3 = {result3} (Evaluated as (20 - 5) - 3)")
result4 = 2 ** 3 ** 2
print(f"2 ** 3 ** 2 = {result4} (Evaluated as 2 ** (3 ** 2))")
