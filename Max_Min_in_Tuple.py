print("--- Find Maximum and Minimum in a Tuple ---")

numbers = (45, 12, 89, 33, 7, 56, 99, 21)

print("Tuple:", numbers)

# Finding max and min using built-in functions
max_value = max(numbers)
min_value = min(numbers)

print(f"Maximum value in the tuple: {max_value}")
print(f"Minimum value in the tuple: {min_value}")
