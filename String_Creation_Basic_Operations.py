# String creation, concatenation, repetition, and slicing
s1 = "Hello"
s2 = "World"

# Concatenation
print("Concatenation:", s1 + " " + s2)

# Repetition
print("Repetition:", s1 * 3)

# Slicing
text = "PythonProgramming"
print("Slice [0:6]:", text[0:6])
print("Slice [6:]:", text[6:])
print("Reverse via slicing:", text[::-1])
